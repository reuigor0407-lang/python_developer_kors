#                              Рівень 3. Побітові операції

#       Завдання 6. Робота з двійковими числами

    # Число А         Число В         Операція        Результат в двійковій         Результат в десятковій
    # 5               3               A & B           101 & 011 = 001               1
    # 5               3               A | B           101 | 011 = 011               7
    # 5               3               A ^ B           101 ^ 011 = 110               6
    # 12              10              A & B           1100 & 1010 = 1000            8
    # 12              10              A | B           1100 | 1010 = 1110            14
    # 12              10              A ^ B           1100 ^ 1010 = 0110            6
    # 8               -               ~A             ~1000                          -9
    # 5               -               A << 2          101 -> 10100                  20
    # 20              -               A >> 2          10100 -> 00101                5

print("5 & 3 =", 5 & 3, bin(5 & 3))
print("5 | 3 =", 5 | 3, bin(5 | 3))
print("5 ^ 3 =", 5 ^ 3, bin(5 ^ 3))

print("12 & 10 =", 12 & 10, bin(12 & 10))
print("12 | 10 =", 12 | 10, bin(12 | 10))
print("12 ^ 10 =", 12 ^ 10, bin(12 ^ 10))

print("~8 =", ~8, bin(~8))
print("5 << 2 =", 5 << 2, bin(5 << 2))
print("20 >> 2 =", 20 >> 2, bin(20 >> 2))

# В Python результат для чисел з побітовим НЕ (~) можливо розрахувати за формуло:
# ~A = -(A + 1)
# Саме тому:
# ~5 = -(5 + 1) = -6
