#       Завдання 10. Множинний вибір — система оцінювання

points = int(input("Введіть кількість балів: "))

if 0 <= points <= 100:
    if points <= 59:
        print("Оцінка F")
    elif points <= 69:
        print("Оцінка D")
    elif points <= 79:
        print("Оцінка C")
    elif points <= 89:
        print("Оцінка B")
    elif points <= 100:
        print("Оцінка A")
else:
    print("Бали повинні бути в діапазоні від 0 до 100")

# Порядок важливий тому що спочатку ми перевірили, що бали входять в діапазон від 0 до 100, і тільки
# після цього якщо умова виконалась ми переходимо до пошуку в якому діапазоні знаходяться наші бали.
# Оскільки Python виконує програму послідовно по рядках, то ми перевіряємо від молодшого діапазону оцінювання до старшого,
# коли програма знайде потрібний діапазон - програма зупиниться та напише нам результат.
